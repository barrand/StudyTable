import assert from 'node:assert/strict';
import { ownerSdk, PROJECT } from './firebase-owner';
import { generateWithGemini } from '../src/server/gemini';
import { study } from '../src/server/study-service';
import { MemoryStore } from '../src/server/store';
import { DEFAULT_GEMINI_MODEL } from '../src/lib/study-versions';
import { readConversation } from '../src/server/conversation';
const sdk=await ownerSdk();
const key=(await sdk.secretManager.accessSecretVersion(PROJECT,'STUDY_GEMINI_API_KEY','latest') as string).trim();
const model=DEFAULT_GEMINI_MODEL;const store=new MemoryStore();let calls=0;
const secret='owner-conversation-validation-not-deployed';
const config={store,secret,model,perKeyLimit:3,globalLimit:3,generate:async(input:Parameters<typeof generateWithGemini>[0],context:unknown)=>{calls++;return generateWithGemini(input,context,{key,model});}};
const base={reference:'John 3:16',translation:'WEB'} as const;
const first=await study({...base,action:'ask',question:'How does this verse relate to the earlier discussion with Nicodemus?'},'owner-smoke',config);
assert(first.conversationToken);assert(first.result.observations.length>0);
const second=await study({...base,action:'ask',question:'Which event in earlier scripture helps explain that discussion?',conversationToken:first.conversationToken},'owner-smoke',config);
assert.equal(readConversation(second.conversationToken,base.reference,base.translation,secret).length,2);
assert(second.result.relatedReferences.length>0);
const related=await study({...base,action:'related'},'owner-smoke',config);assert(related.result.relatedReferences.length>0);
const cached=await study({...base,action:'related'},'other-visitor',config);assert(cached.cached);assert.equal(calls,3);
assert(!JSON.stringify([...store.records.values()]).includes('Nicodemus?'));
console.log('Live Gemini ask, signed-context follow-up, and related-verses checks passed; custom conversations were not persisted and the standard related response was reused.');
